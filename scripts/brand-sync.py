"""Regenerate the generated brand consumers of this repo (stdlib only).

    uv run python scripts/brand-sync.py           # write targets
    uv run python scripts/brand-sync.py --check   # exit 1 if any target drifted

The host shell wears the design system its tenants use: its Streamlit config is
a verbatim mirror of the analytics app's hand-maintained one (fonts, static
serving and all; host/static links to the same static folder). Edit the app's
config, never the mirror; tests/test_brand.py re-renders and diffs. The TUI
brand (OpenCode theme, braille marks) lives in sojourner.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "src" / "new_horizons"
STREAMLIT_CONFIG = PKG / "app" / ".streamlit" / "config.toml"
# Streamlit also reads .streamlit/ next to the main script: the host needs its own.
HOST_CONFIG = PKG / "host" / ".streamlit" / "config.toml"


def render_host_config() -> str:
    return ("# GENERATED by scripts/brand-sync.py — mirror of\n"
            "# app/.streamlit/config.toml. Edit that, then run scripts/brand-sync.py.\n\n"
            + STREAMLIT_CONFIG.read_text(encoding="utf-8"))


def targets() -> dict[Path, str]:
    return {HOST_CONFIG: render_host_config()}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    drifted = []
    for path, text in targets().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        drifted.append(path.relative_to(ROOT))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    verb = "drifted" if check else "written"
    for p in drifted:
        print(f"{verb}: {p}")
    if not drifted:
        print("brand: all targets up to date")
    return 1 if (check and drifted) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
